def model_case(temperature=2500.0, duration=1.0e-3):
    handoff, propagation, bc, reactive = synthetic_condensed_case(
        shape=(5, 5), rates=(2.0, 1.0), heats=(1000.0, 2000.0),
        alpha=(0.1, 0.2),
    )
    handoff["temperatureAtOnset_K"][:] = min(temperature, 2490.0)
    handoff["temperatureAtOnset_K"][1, 2] = temperature
    bc["thermal"]["maximumTemperature_K"] = 2500.0
    propagation.update(duration_s=duration, time_step_s=duration,
                       snapshot_interval_s=duration)
    reactive.update(chemistry_integration_mode="local_adaptive_thermochemical",
                    stationary_mechanics_fast_path=True, riemann_solver="hllc")
    adapted = PreflameReactiveHandoffAdapter(propagation, bc, reactive).adapt(handoff)
    return CondensedReactiveSolver(adapted, propagation, bc, reactive,
                            initialize_electrical=False)


@pytest.mark.parametrize("temperature,dt,valid", [
    (2499.0, 1.0e-3, True),
    (2500.0, 0.0, True),
    (2500.0, 5.0e-11, True),  # Positive overshoot inside the ORIGINAL allowance.
    (2500.0, 1.0e-3, False),
])
def test_unchanged_temperature_boundary_numpy_torch(temperature, dt, valid):
    solver = model_case(temperature)
    before = solver.U.copy()
    kernel = TensorCondensedKernel([solver], "cpu")
    tensor_after, tensor_valid, row = kernel.advance_local(
        kernel.initial, kernel.tensor([dt]))
    diagnostics = dict(zip(LOCAL_CHEMISTRY_DIAGNOSTIC_NAMES, row[0].tolist()))
    assert bool(tensor_valid[0]) is valid
    if valid:
        after, _ = solver.chem.advance_local(
            solver.U, solver.thermo, dt, **scalar_local_kwargs(solver))
        np.testing.assert_allclose(tensor_after[0].numpy(), after, rtol=2e-15, atol=1e-10)
        assert diagnostics[RangeError.code] == 0.0
        if dt == 5.0e-11:
            final_t = solver.thermo.primitive(after)[..., 3].max()
            assert 2500.0 < final_t <= 2500.0 + 256*np.finfo(float).eps*final_t
    else:
        with pytest.raises(RangeError) as captured:
            solver.chem.advance_local(
                solver.U, solver.thermo, dt, **scalar_local_kwargs(solver))
        error = captured.value
        assert isinstance(error, PropagationCandidateModelValidityError)
        assert not isinstance(error, PropagationCandidateNumericalError)
        assert error.cell_index == 7  # Original (1, 2), not a compacted index.
        assert diagnostics[RangeError.code] == 1.0
        assert diagnostics["offending_temperature_cell_index"] == 7
        assert diagnostics["observed_maximum_temperature_K"] == pytest.approx(
            error.observed_maximum, abs=1e-12)
        assert error.observed_maximum > 2500.0 + error.roundoff_tolerance
        np.testing.assert_array_equal(tensor_after[0].numpy(), before)
    np.testing.assert_array_equal(solver.U, before)
    np.testing.assert_array_equal(kernel.initial[0].numpy(), before)


def test_valid_numpy_and_torch_retain_exact_prepatch_golden_state():
    solver = model_case(300.0)
    expected_cell = np.asarray([
        1000.0, 0.0, 0.0, 4270000.0, 200.0, 250.0,
        113.58333333333334, 113.58333333333334, 50.0,
        78.33333333333334, 43.33333333333333, 0.0,
    ])
    after, _ = solver.chem.advance_local(
        solver.U, solver.thermo, 0.05, **scalar_local_kwargs(solver))
    kernel = TensorCondensedKernel([solver], "cpu")
    tensor_after, valid, _ = kernel.advance_local(kernel.initial, kernel.tensor([0.05]))
    assert bool(valid[0])
    expected = np.broadcast_to(expected_cell, solver.U.shape)
    np.testing.assert_array_equal(after, expected)
    np.testing.assert_array_equal(tensor_after[0].numpy(), expected)


def test_range_error_cpu_worker_pickle_and_numerical_failure_remain_distinct():
    error = RangeError(2500.0, 2500.0012922586584, 32337, 1.4210862060842023e-10)
    recovered = pickle.loads(pickle.dumps(error))
    assert type(recovered) is RangeError
    assert str(recovered) == str(error)
    metrics = candidate_failure_payload(recovered)
    assert metrics["propagationSucceeded"] is False
    assert metrics["postOnsetModelValid"] is False
    assert metrics["postOnsetValidityConstraintViolation"] == 1.0
    assert metrics["postOnsetValidityReason"] == RangeError.code
    assert metrics["offendingCellIndex"] == 32337
    json.dumps(metrics, allow_nan=False)
    numerical = PropagationCandidateNumericalError(RangeError.code)
    assert candidate_failure_payload(numerical) == {
        "status": "failed", "errorType": "PropagationCandidateNumericalError",
        "message": RangeError.code,
    }  # Even identical text cannot create a validity classification.


@pytest.mark.parametrize("half", [1, 2])
def test_scalar_range_rejection_rolls_back_whole_trial(tmp_path, monkeypatch, half):
    solver = model_case(300.0)
    before = solver.U.copy()
    original = solver._chemistry_half_step
    calls = []
    checkpoints = []

    def chemistry(state, dt):
        calls.append(state.copy())
        if len(calls) == half:
            raise RangeError(2500, 2500.001, 7, 1.42e-10)
        return original(state, dt)

    monkeypatch.setattr(solver, "_chemistry_half_step", chemistry)
    monkeypatch.setattr(solver, "_restore_electrical_checkpoint", checkpoints.append)
    with pytest.raises(RangeError):
        solver.run(tmp_path)
    assert len(calls) == half  # No timestep retry.
    assert len(checkpoints) == 1
    assert solver.step_number == 0
    assert solver.rejected_steps == 1
    np.testing.assert_array_equal(solver.U, before)
    with np.load(tmp_path / "INCOMPLETE_STATE.npz") as saved:
        np.testing.assert_array_equal(saved["U"], before)
        assert saved["time_after_onset_s"] == 0
    assert not (tmp_path / "propagation_metrics.json").exists()
    metrics = json.loads((tmp_path / "PROPAGATION_FAILED.json").read_text())
    assert metrics["failureCode"] == RangeError.code


def test_tensor_range_failure_is_lane_local_and_success_unchanged(tmp_path):
    failed, valid, reference = model_case(), model_case(300), model_case(300)
    before = failed.U.copy()
    results = run_tensor_solvers([failed, valid], [tmp_path / "bad", tmp_path / "good"],
                                {"backend": "torch_batch"})
    baseline = run_tensor_solvers([reference], [tmp_path / "reference"],
                                 {"backend": "torch_batch"})[0]
    assert isinstance(results[0], RangeError)
    assert results[0].cell_index == 7
    assert results[1]["status"] == "complete"
    assert results[1]["postOnsetModelValid"] is True
    assert failed.step_number == 0
    np.testing.assert_array_equal(failed.U, before)
    np.testing.assert_array_equal(valid.U, reference.U)
    for key in ("finalUnreactedAreaFraction", "establishedTimeAfterOnset_s",
                "meanEffectiveRegressionVelocity_m_per_s", "reactionFrontNonuniformity"):
        assert results[1][key] == baseline[key]
    saved = json.loads((tmp_path / "bad" / "PROPAGATION_FAILED.json").read_text())
    assert saved["postOnsetValidityReason"] == RangeError.code










def test_post_onset_writer_preserves_typed_failure(tmp_path, monkeypatch):
    from ecsp_preflame.post_onset import run_post_onset
    from ecsp_reactive.condensed import solver as solver_module
    h, p, b, r = synthetic_condensed_case(shape=(5, 5))

